// Builds the game's map and state-seat list from DOSM's open data (dosm-malaysia/data-open, Open Data License).
//   1. Download into data/raw/: electoral_0_parlimen.geojson, electoral_1_dun.geojson, state_parlimen_dun.csv
//   2. node scripts/build-map.mjs
// Outputs public/data/malaysia.topo.json (parlimen, dun and states layers, simplified) and src/game/data/duns.ts.

import fs from "node:fs";
import mapshaper from "mapshaper";

const RAW = "data/raw";
const OUT_MAP = "public/data/malaysia.topo.json";
const OUT_DUNS = "src/game/data/duns.ts";

// DOSM state names → the game's state ids (src/game/world.ts).
const STATE_ID = {
  Perlis: "PLS",
  Kedah: "KDH",
  Kelantan: "KTN",
  Terengganu: "TRG",
  "Pulau Pinang": "PNG",
  Perak: "PRK",
  Pahang: "PHG",
  Selangor: "SGR",
  "W.P. Kuala Lumpur": "KUL",
  "W.P. Putrajaya": "PJY",
  "Negeri Sembilan": "NSN",
  Melaka: "MLK",
  Johor: "JHR",
  "W.P. Labuan": "LBN",
  Sabah: "SBH",
  Sarawak: "SWK",
};

fs.mkdirSync("public/data", { recursive: true });
fs.mkdirSync("src/game/data", { recursive: true });

// Parliament seats are built by merging their state seats (plus the three federal territories, which have none),
// so every layer shares the same boundary lines and the file stays small.
await mapshaper.runCommands(
  [
    `-i ${RAW}/electoral_1_dun.geojson ${RAW}/electoral_0_parlimen.geojson combine-files snap`,
    "-rename-layers dun,ft",
    "-filter 'code_state === 14 || code_state === 15 || code_state === 16' target=ft",
    "-filter-fields code_parlimen,code_state target=ft",
    "-filter-fields code_state_dun,code_parlimen,code_state target=dun",
    "-filter-islands min-area=1.5km2 remove-empty target=dun,ft",
    "-clean snap-interval=0.0001 allow-empty target=dun,ft",
    "-dissolve code_parlimen copy-fields=code_state target=dun + name=pdun",
    "-merge-layers target=pdun,ft name=parlimen force",
    "-dissolve code_state target=parlimen + name=states",
    "-simplify 25% weighted keep-shapes target=*",
    `-o ${OUT_MAP} format=topojson quantization=20000 target=dun,parlimen,states`,
  ].join(" "),
);

const rows = fs
  .readFileSync(`${RAW}/state_parlimen_dun.csv`, "utf8")
  .trim()
  .split(/\r?\n/)
  .slice(1)
  .map((l) => l.split(","))
  .filter((c) => c[2]); // federal territories have no state seats
const duns = rows.map(([state, , dun, , codeParlimen, codeDun, codeStateDun]) => {
  if (!STATE_ID[state]) throw new Error(`Unknown state ${state}`);
  return [STATE_ID[state], codeParlimen, codeDun, dun.replace(/^N\.\d+\s+/, ""), codeStateDun];
});

fs.writeFileSync(
  OUT_DUNS,
  `// Generated by scripts/build-map.mjs from DOSM open data (dosm-malaysia/data-open). Do not edit by hand.
// [stateId, parliamentary seat code, state seat code, name, DOSM map key]
export const DUN_ROWS: [string, string, string, string, string][] = ${JSON.stringify(duns)};
`,
);

console.log(`${OUT_MAP}: ${(fs.statSync(OUT_MAP).size / 1024).toFixed(0)} KB · ${OUT_DUNS}: ${duns.length} state seats`);
